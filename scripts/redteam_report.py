"""Run the red-team suite and write docs/REDTEAM.md (pass/fail per case and per category).

    python scripts/redteam_report.py            # deterministic layers only (LLM_PROVIDER=none)
    LLM_PROVIDER=anthropic python scripts/redteam_report.py   # also exercises the LLM layers
"""
import os
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import Counter
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
xml = ROOT / ".pytest_cache" / "redteam.xml"
xml.parent.mkdir(exist_ok=True)
subprocess.run([sys.executable, "-m", "pytest", "-q", str(ROOT / "tests" / "test_redteam.py"), f"--junitxml={xml}"], cwd=ROOT)
cases = {c["id"]: c for c in yaml.safe_load((ROOT / "tests" / "redteam.yaml").read_text())["cases"]}
res = {}
for tc in ET.parse(xml).getroot().iter("testcase"):
    cid = tc.get("name").split("[", 1)[1].rstrip("]")
    res[cid] = "FAIL" if (tc.find("failure") is not None or tc.find("error") is not None) else "pass"
by = Counter()
tot = Counter()
for cid, c in cases.items():
    cat = c["category"].split("-")[0]
    tot[cat] += 1
    by[cat] += res.get(cid) == "pass"
passed = sum(v == "pass" for v in res.values())
lines = [f"# Red-team results", "", f"Run: {date.today().isoformat()} · LLM provider: `{os.environ.get('LLM_PROVIDER', 'none')}` · "
         f"**{passed}/{len(cases)} passed**", "",
         "Generated by `scripts/redteam_report.py` from `tests/redteam.yaml`. With `LLM_PROVIDER=none` this tests the",
         "deterministic layers (keyword crisis detection, scope guardrails, consent/age gates, deletion).", "",
         "| Category | Passed |", "|---|---|"]
lines += [f"| {k} | {by[k]}/{tot[k]} |" for k in sorted(tot)]
lines += ["", "| ID | Lang | Input | Result |", "|---|---|---|---|"]
for cid, c in cases.items():
    inp = (c.get("input") or f"[button {c.get('button')}]").replace("|", "\\|")
    lines.append(f"| {cid} | {c.get('lang', 'en')} | {inp} | {res.get(cid, 'not run')} |")
(ROOT / "docs" / "REDTEAM.md").write_text("\n".join(lines) + "\n")
print(f"{passed}/{len(cases)} passed -> docs/REDTEAM.md")

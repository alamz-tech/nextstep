"""Session report PDF for donor reporting. Aggregate numbers only."""
from __future__ import annotations

import io

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

PRIMARY = colors.HexColor("#0F5C5A")
LABELS = {
    "session_date": "Session date", "setting": "Setting", "audience_age_band": "Audience age band",
    "approximate_reach": "Approximate reach (facilitator estimate)", "anonymous_joins": "Anonymous question-box joins",
    "questions_submitted": "Questions submitted", "crisis_flags": "Questions flagged for support (count only)",
    "filtered_submissions": "Submissions filtered (pranks/abuse)", "referral_cards_issued": "Referral codes issued from this session",
}


def session_report_pdf(d: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, title="NextStep session report", leftMargin=48, rightMargin=48)
    ss = getSampleStyleSheet()
    h = ss["Title"]
    h.textColor = PRIMARY
    story = [Paragraph("NextStep session report", h),
             Paragraph("Aggregate figures only. No names, phone numbers or individual answers are collected.", ss["Normal"]),
             Spacer(1, 12)]
    rows = [["Metric", "Value"]] + [[LABELS[k], str(v).replace("_", "–") if k == "audience_age_band" else str(v)]
                                     for k, v in d.items() if k in LABELS]
    t = Table(rows, colWidths=[330, 150])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), PRIMARY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                           ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E3DFD7")), ("PADDING", (0, 0), (-1, -1), 6)]))
    story += [t, Spacer(1, 18), Paragraph("Question themes", ss["Heading2"])]
    th = [["Theme", "Questions", "Answered"]] + [[Paragraph(x["label"], ss["Normal"]), str(x["count"]), "yes" if x["answered"] else "no"]
                                                  for x in d["themes"]] or [["–", "0", ""]]
    t2 = Table(th, colWidths=[330, 80, 70])
    t2.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), PRIMARY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E3DFD7")), ("PADDING", (0, 0), (-1, -1), 6)]))
    story += [t2, Spacer(1, 18), Paragraph("Generated by NextStep (open source, MIT). Health content is draft pending clinician review.", ss["Italic"])]
    doc.build(story)
    return buf.getvalue()
